from __future__ import annotations

import io

import pandas as pd
import streamlit as st

from components import ui
from services import csvio, finance as fin
from utils.format import month_label, pct


def _csv(df: pd.DataFrame) -> bytes:
    d = df.copy()
    for c in d.select_dtypes(include="object"):
        d[c] = d[c].map(csvio.safe_cell)
    return d.to_csv(index=False).encode("utf-8-sig")


def render(ctx) -> None:
    ds, m = ctx.ds, ctx.m
    ui.page_header("Reports", "Summaries you can download or print.")
    if ds.tx.empty:
        return ui.empty_state("No data to report on", "Record transactions first.")
    lo, hi = ds.tx["transaction_date"].min().date(), ds.tx["transaction_date"].max().date()
    r = st.date_input("Period", value=(max(lo, (ctx.month - pd.DateOffset(months=5)).date()), min(hi, fin.month_end(ctx.month).date())))
    if not isinstance(r, tuple) or len(r) != 2:
        return st.info("Pick a start and an end date.")
    start, end = pd.Timestamp(r[0]), pd.Timestamp(r[1])
    tx = ds.tx[(ds.tx["transaction_date"] >= start) & (ds.tx["transaction_date"] <= end)]
    if tx.empty:
        return st.info("No transactions in that period.")
    s = fin.monthly_summary(tx).reset_index()
    s["Month"] = s["month"].map(month_label)
    cats = fin.category_spend(ds.tx, start, end)
    tot = fin.monthly_summary(tx)[["income", "consumption", "investment", "net_cash_flow"]].sum()

    k = st.columns(4)
    for col, (l, v) in zip(k, [("Income", tot["income"]), ("Spending", tot["consumption"]), ("Invested", tot["investment"]), ("Net cash flow", tot["net_cash_flow"])]):
        col.markdown(ui.kpi(l, m(v)), unsafe_allow_html=True)
    st.markdown("### By month")
    ui.html_table(s, [("Month", "Month", "l", None), ("income", "Income", "r", m), ("consumption", "Spending", "r", m), ("investment", "Invested", "r", m),
                      ("net_cash_flow", "Net cash flow", "r", m), ("savings_rate", "Savings rate", "r", pct)])
    st.markdown("### By category")
    ui.html_table(cats, [("category", "Category", "l", None), ("classification", "Class", "l", str.title), ("amount", "Spent", "r", m)])

    st.markdown("### Download")
    c = st.columns(3)
    c[0].download_button("Transactions (CSV)", csvio.export_transactions(tx, ds.accounts), f"finlife-transactions-{start:%Y%m%d}-{end:%Y%m%d}.csv", "text/csv")
    c[1].download_button("Monthly summary (CSV)", _csv(s.drop(columns=["Month"])), "finlife-monthly-summary.csv", "text/csv")
    c[2].download_button("Printable report (HTML)", _html_report(ctx, s, cats, start, end, tot), f"finlife-report-{start:%Y%m%d}-{end:%Y%m%d}.html", "text/html")
    st.caption("Open the HTML report in your browser and use Print > Save as PDF.")


def _html_report(ctx, s, cats, start, end, tot) -> bytes:
    e, m = ui.esc, ctx.m
    rows = "".join(f"<tr><td>{e(r['Month'])}</td><td class=r>{e(m(r['income']))}</td><td class=r>{e(m(r['consumption']))}</td><td class=r>{e(m(r['investment']))}</td>"
                   f"<td class=r>{e(m(r['net_cash_flow']))}</td></tr>" for _, r in s.iterrows())
    crow = "".join(f"<tr><td>{e(r['category'])}</td><td class=r>{e(m(r['amount']))}</td></tr>" for _, r in cats.iterrows())
    name = e(ctx.profile.get("full_name") or ctx.session.email)
    doc = f"""<!doctype html><html><head><meta charset="utf-8"><title>FinLife report</title><style>
body{{font:14px/1.5 Inter,system-ui,sans-serif;color:#172B4D;max-width:800px;margin:2rem auto;padding:0 1rem}}h1{{color:#142B4A}}
table{{width:100%;border-collapse:collapse;margin:.5rem 0 1.5rem}}th,td{{padding:.4rem .6rem;border-bottom:1px solid #DCE6F3;text-align:left}}.r{{text-align:right}}
th{{background:#EAF2FF}}</style></head><body><h1>FinLife report</h1><p>{name} · {start:%d %b %Y} to {end:%d %b %Y}</p>
<p>Income <b>{e(m(tot['income']))}</b> · Spending <b>{e(m(tot['consumption']))}</b> · Invested <b>{e(m(tot['investment']))}</b> · Net cash flow <b>{e(m(tot['net_cash_flow']))}</b></p>
<h2>By month</h2><table><tr><th>Month</th><th class=r>Income</th><th class=r>Spending</th><th class=r>Invested</th><th class=r>Net cash flow</th></tr>{rows}</table>
<h2>Spending by category</h2><table><tr><th>Category</th><th class=r>Spent</th></tr>{crow}</table>
<p style="color:#64748B">Generated by FinLife from values you entered. Not financial advice.</p></body></html>"""
    return doc.encode("utf-8")
